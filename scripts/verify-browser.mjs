/** Chromium UI smoke checks against the local synthetic demo; requires playwright-cli. */
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, writeFile, readFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import dotenv from 'dotenv';

dotenv.config({ path: '.env.local', quiet: true });
const run = promisify(execFile);
const base = process.env.MEDIFLOW_DEMO_URL ?? 'http://127.0.0.1:3000';
const url = new URL(base);
assert.ok(['127.0.0.1', 'localhost'].includes(url.hostname) && url.protocol === 'http:', 'Local demo only');
const password = process.env.DEMO_DOCTOR_PASSWORD, receptionistPassword = process.env.DEMO_RECEPTIONIST_PASSWORD;
assert.ok(password && receptionistPassword, 'Configure demo passwords in .env.local');
const system = JSON.parse(await readFile('eval/results/system-verification.json', 'utf8'));
assert.equal(system.status, 'passed', 'Run verify:system first to create the synthetic completed prescription');
const directory = await mkdtemp(join(tmpdir(), 'mediflow-browser-'));
const file = join(directory, 'scenario.js');
const session = 'mediflow-verification';
const scenario = `async page => {
  const checks = [], errors = [];
  const base = ${JSON.stringify(base)};
  const password = ${JSON.stringify(password)};
  const receptionistPassword = ${JSON.stringify(receptionistPassword)};
  const completedId = ${JSON.stringify(system.synthetic_records.completed_consultation_id)};
  const reviewId = ${JSON.stringify(system.synthetic_records.review_consultation_id)};
  const name = 'SYNTHETIC Browser ' + Date.now();
  const phone = '+1555' + String(Date.now()).slice(-7);
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  const doctorLogin = async () => {
    await page.goto(base + '/login');
    await page.getByLabel('Email', { exact: true }).fill('demo-doctor-a@mediflow.invalid');
    await page.getByLabel('Password', { exact: true }).fill(password);
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    await page.waitForURL('**/doctor', { timeout: 15000 });
  };
  try {
    await page.context().clearCookies();
    await page.goto(base + '/doctor');
    check(page.url().includes('/login'), 'unauthenticated doctor page redirects to login');
    await doctorLogin(); check(page.url().endsWith('/doctor'), 'doctor login and dashboard render');
    await page.goto(base + '/doctor/patients');
    await page.getByRole('button', { name: 'Add New Patient', exact: true }).click();
    await page.getByRole('button', { name: 'Save Patient', exact: true }).click();
    await page.getByText('Patient name is required.', { exact: true }).waitFor();
    check(true, 'patient form validates required fields');
    await page.getByLabel('Full Name*', { exact: true }).fill(name);
    await page.getByLabel('Phone*', { exact: true }).fill(phone);
    await page.getByLabel('Allergies (comma-separated)', { exact: true }).fill('Penicillin');
    const created = page.waitForResponse(r => r.url().endsWith('/api/patients/create') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Save Patient', exact: true }).click();
    const createResponse = await created;
    check(createResponse.status() === 200, 'doctor creates patient through browser form');
    const patientId = (await createResponse.json()).id;
    await page.getByText('Patient added successfully.', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByPlaceholder('Search by name, phone, ABHA ID').fill(phone);
    await page.getByText(name, { exact: true }).first().waitFor();
    check(true, 'patient list search finds newly registered patient');
    await page.goto(base + '/doctor/patients/' + patientId);
    await page.getByText(name, { exact: true }).first().waitFor();
    check(true, 'patient details and history page render');
    await page.goto(base + '/doctor/settings');
    await page.getByLabel('Clinic / hospital name', { exact: true }).fill('SYNTHETIC Demo Clinic');
    await page.getByRole('button', { name: 'Save clinic details', exact: true }).click();
    await page.getByText('Clinic settings updated.', { exact: true }).waitFor();
    check(true, 'clinic settings save through browser');
    await page.getByLabel('Receptionist password', { exact: true }).fill('short123');
    check(await page.getByRole('button', { name: 'Save', exact: true }).isDisabled(), 'password UI enforces ten-character minimum');
    await page.getByLabel('Receptionist password', { exact: true }).fill('');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(base + '/doctor');
    check(await page.locator('h1').count() > 0, 'mobile dashboard renders');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile dashboard has no page-level horizontal overflow');
    await page.screenshot({ path: '.playwright-cli/mediflow-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1365, height: 900 });
    await page.getByRole('button', { name: 'Profile menu', exact: true }).click();
    await page.getByRole('button', { name: 'Logout', exact: true }).click();
    await page.waitForURL('**/login'); check(true, 'doctor logout returns to login');
    await page.goto(base + '/receptionist/login');
    await page.getByLabel('Doctor email', { exact: true }).fill('demo-doctor-a@mediflow.invalid');
    await page.getByLabel('Receptionist password', { exact: true }).fill(receptionistPassword);
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    await page.waitForURL('**/receptionist/patients'); check(true, 'receptionist login renders scoped dashboard');
    await page.getByLabel('Patient', { exact: true }).fill(name);
    await page.getByRole('button', { name, exact: true }).click();
    await page.getByLabel('Chief complaint', { exact: true }).fill('SYNTHETIC browser headache');
    const intake = page.waitForResponse(r => r.url().endsWith('/api/consultations/create') && r.request().method() === 'POST');
    await page.getByRole('button', { name: 'Save Intake and Create Consultation', exact: true }).click();
    const intakeResponse = await intake;
    check(intakeResponse.status() === 200, 'receptionist starts consultation through intake UI');
    const consultationId = (await intakeResponse.json()).consultation_id;
    await page.getByText('Intake saved. Doctor can continue this consultation.', { exact: true }).waitFor();
    check(true, 'receptionist intake EMR and completion marker persist');
    await page.goto(base + '/doctor');
    await page.waitForURL(url => url.pathname === '/receptionist/patients'); check(true, 'receptionist is redirected away from doctor routes');
    await page.request.post(base + '/api/auth/logout');
    await page.context().clearCookies();
    await doctorLogin();
    await page.goto(base + '/doctor/consultation/' + consultationId);
    await page.getByLabel('Chief complaint', { exact: true }).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('input,textarea')].some(input => input.value.includes('browser headache')));
    check((await page.getByLabel('Chief complaint', { exact: true }).inputValue()).includes('browser headache'), 'doctor workspace loads receptionist intake');
    const save = page.waitForResponse(r => r.url().includes('/api/emr/by-consultation/') && r.request().method() === 'PUT');
    await page.getByLabel('Pulse rate', { exact: true }).fill('82');
    check((await save).status() === 200, 'EMR browser autosave succeeds');
    await page.reload();
    await page.getByLabel('Pulse rate', { exact: true }).waitFor();
    await page.waitForFunction(() => [...document.querySelectorAll('input')].some(input => input.value === '82'));
    check(await page.getByLabel('Pulse rate', { exact: true }).inputValue() === '82', 'EMR changes survive browser reload');
    await page.screenshot({ path: '.playwright-cli/mediflow-workspace.png', fullPage: true });
    await page.goto(base + '/doctor/consultation/' + reviewId);
    await page.getByLabel('Chief complaint', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Review & Complete', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Clinician Review & Sign-Off', exact: true });
    await dialog.waitFor();
    const complete = dialog.getByRole('button', { name: 'Approve & Complete Consultation', exact: true });
    check(await complete.isDisabled(), 'clinical sign-off requires explicit confirmations');
    await dialog.getByRole('checkbox', { name: "I personally verified the patient's allergy status." }).check();
    await dialog.getByRole('checkbox', { name: 'I checked medication identities, instructions, and prescribing safety.' }).check();
    await dialog.getByRole('checkbox', { name: /I reviewed this entire EMR and approve version/ }).check();
    if (!await complete.isEnabled()) throw new Error('Review remains blocked after confirmations: ' + (await dialog.innerText()));
    check(true, 'review becomes ready after explicit confirmations');
    const completion = page.waitForResponse(r => r.url().endsWith('/api/consultations/' + reviewId) && r.request().method() === 'PATCH');
    await complete.click();
    check((await completion).status() === 200, 'doctor reviews and completes consultation through browser');
    await page.getByText('Consultation completed with doctor-approved EMR', { exact: true }).waitFor();
    await page.reload();
    check(await page.getByRole('button', { name: 'Review & Complete', exact: true }).isDisabled(), 'completed consultation stays locked after reload');
    await page.goto(base + '/doctor/consultations');
    check((await page.locator('body').innerText()).includes('Consultations'), 'consultation list renders');
    await page.goto(base + '/doctor/consultations/' + completedId);
    await page.getByText('Transcript', { exact: true }).click();
    await page.getByText('Paracetamol', { exact: false }).first().waitFor();
    check(true, 'completed encounter details render');
    await page.goto(base + '/doctor/consultations/' + completedId + '/prescription');
    await page.getByText('Paracetamol', { exact: false }).first().waitFor();
    await page.emulateMedia({ media: 'print' });
    await page.screenshot({ path: '.playwright-cli/mediflow-prescription.png', fullPage: true });
    check(true, 'approved prescription renders in print media');
    check(errors.length === 0, 'no uncaught browser JavaScript errors');
    return { status: 'passed', checks, errors, synthetic_records: { patient_id: patientId, consultation_id: consultationId } };
  } catch (error) {
    await page.screenshot({ path: '.playwright-cli/mediflow-failure.png', fullPage: true }).catch(() => {});
    return { status: 'failed', checks, errors, failure: error.message, url: page.url() };
  }
}`;
const redact = text => [password, receptionistPassword, process.env.AUTH_SECRET, process.env.GROQ_API_KEY, process.env.DEEPGRAM_API_KEY]
  .filter(Boolean).reduce((value, secret) => value.split(secret).join('[REDACTED]'), text);
try {
  await mkdir('.playwright-cli', { recursive: true });
  await writeFile(file, scenario, { mode: 0o600 });
  await run('playwright-cli', [`-s=${session}`, 'open', `${base}/login`], { timeout: 30000 });
  const result = await run('playwright-cli', [`-s=${session}`, '--raw', 'run-code', `--filename=${file}`], { timeout: 180000, maxBuffer: 2 * 1024 * 1024 });
  const report = JSON.parse(result.stdout);
  report.executed_at = new Date().toISOString();
  report.scope = 'real Chromium and local production application; no microphone/provider calls';
  await writeFile('eval/results/browser-verification.json', JSON.stringify(report, null, 2) + '\n');
  console.log(redact(JSON.stringify(report, null, 2)));
  if (report.status !== 'passed') process.exitCode = 1;
} catch (error) {
  console.error(redact(error.stdout ?? error.message)); process.exitCode = 1;
} finally {
  await run('playwright-cli', [`-s=${session}`, 'close']).catch(() => {});
  await rm(directory, { recursive: true, force: true });
}
